def get_supply_cols(n_region=164, n_sector=120):
    """
    GLORIA TQ columns are interleaved as SUPPLY / USE.
    This extracts SUPPLY-side columns only.
    """
    supply_cols = []
    for c in range(n_region):
        for s in range(n_sector):
            col_idx = s + n_sector * c * 2
            supply_cols.append(col_idx)
    return np.array(supply_cols)

SUPPLY_COLS = get_supply_cols(N_REGION, N_SECTOR)


def load_ours(year):
    """
    Load our satellite account, expected shape after reshape: 164 × 120
    """
    path = BASE_OURS / f"satellite_{year}.npy"
    if not path.exists():
        print(f"[SKIP] Missing our file: {path}")
        return None

    arr = np.load(path).reshape(N_REGION, N_SECTOR)
    return arr


def load_gloria_ws(year):
    """
    Load GLORIA agriculture water stress row from TQ_{year}.csv,
    then extract supply-side columns and reshape to 164 × 120.
    """
    path = BASE_GLORIA / str(year) / f"TQ_{year}.csv"
    if not path.exists():
        print(f"[SKIP] Missing GLORIA file: {path}")
        return None

    rows_needed = [ROW_WATER_STRESS, ROW_BLUE_WATER_CONSUMPTION]

    gloria_rows = pd.read_csv(
        path,
        header=None,
        skiprows=lambda x: x not in rows_needed
    )

    if gloria_rows.shape[0] < 1:
        print(f"[SKIP] Could not read water-stress row for year {year}")
        return None

    gloria_ws = gloria_rows.iloc[0, SUPPLY_COLS].values.astype(float).reshape(N_REGION, N_SECTOR)
    return gloria_ws


def align_unit(ours, gloria_ws):
    """
    GLORIA is in million m3 H2Oeq.
    If our data is ~1e6 larger, convert ours from m3 to million m3.
    """
    ours_sum = ours[:, :N_CROP_SECTOR].sum()
    gloria_sum = gloria_ws[:, :N_CROP_SECTOR].sum()

    if gloria_sum == 0:
        return ours, 1, np.nan

    ratio = ours_sum / gloria_sum

    if ratio > 1e4:
        scale_factor = 1e6
    else:
        scale_factor = 1

    ours_aligned = ours / scale_factor
    return ours_aligned, scale_factor, ratio


def safe_corr(x, y, method="pearson", min_n=5):
    """
    Safe correlation with finite-value checking.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    mask = np.isfinite(x) & np.isfinite(y)

    if mask.sum() < min_n:
        return np.nan

    x = x[mask]
    y = y[mask]

    if np.all(x == x[0]) or np.all(y == y[0]):
        return np.nan

    if method == "pearson":
        r, _ = stats.pearsonr(x, y)
    elif method == "spearman":
        r, _ = stats.spearmanr(x, y)
    else:
        raise ValueError("method must be 'pearson' or 'spearman'")

    return r


def prepare_density_colors_log(x, y):
    """
    Compute density in log10 space using gaussian_kde,
    then return x, y, normalized density sorted from low to high density.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    mask = np.isfinite(x) & np.isfinite(y) & (x > 0) & (y > 0)
    x = x[mask]
    y = y[mask]

    if len(x) < 5:
        return x, y, None

    xy_log = np.vstack([np.log10(x), np.log10(y)])
    z = stats.gaussian_kde(xy_log)(xy_log)

    # sort so low-density points are drawn first, high-density points last
    idx = z.argsort()
    x = x[idx]
    y = y[idx]
    z = z[idx]

    # normalize to 0-1 for nicer colorbar
    z = (z - z.min()) / (z.max() - z.min() + 1e-12)

    return x, y, z


def load_period_mean(period_name, years):
    """
    Load all valid years in a period, align units year by year,
    keep first 14 crop-growing sectors, then compute period mean.
    """
    ours_list = []
    gloria_list = []
    used_years = []
    unit_records = []

    for year in years:
        ours = load_ours(year)
        gloria_ws = load_gloria_ws(year)

        if ours is None or gloria_ws is None:
            continue

        ours_mm3, scale_factor, ratio = align_unit(ours, gloria_ws)

        ours_crop = ours_mm3[:, :N_CROP_SECTOR]
        gloria_crop = gloria_ws[:, :N_CROP_SECTOR]

        ours_list.append(ours_crop)
        gloria_list.append(gloria_crop)
        used_years.append(year)

        unit_records.append({
            "period": period_name,
            "year": year,
            "scale_factor_applied_to_ours": scale_factor,
            "raw_unit_ratio_ours_over_gloria": ratio,
            "ours_total_first14_million_m3": ours_crop.sum(),
            "gloria_total_first14_million_m3": gloria_crop.sum(),
        })

    if len(ours_list) == 0:
        raise ValueError(f"No valid years found for period {period_name}")

    ours_mean = np.nanmean(np.stack(ours_list, axis=0), axis=0)
    gloria_mean = np.nanmean(np.stack(gloria_list, axis=0), axis=0)

    return ours_mean, gloria_mean, used_years, unit_records


