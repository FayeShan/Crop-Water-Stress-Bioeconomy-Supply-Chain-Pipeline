# GLORIA constants
N_REGIONS = 164
N_SECTORS = 120
N_FD_CATEGORIES = 6
MRIO_SIZE = N_REGIONS * N_SECTORS  # 19,680

def load_gloria_csv(filepath, dtype=np.float32):
    """Load GLORIA CSV file"""
    data = np.loadtxt(filepath, delimiter=',', dtype=dtype)
    return data


def sut_to_mrio_T(T_sut, dtype=np.float32):
    """T from SUT to MRIO format"""
    T_mrio = np.zeros((MRIO_SIZE, MRIO_SIZE), dtype=dtype)

    for c1 in range(N_REGIONS):
        for c2 in range(N_REGIONS):
            r1, r2 = c1 * N_SECTORS, (c1 + 1) * N_SECTORS
            c1_idx, c2_idx = c2 * N_SECTORS, (c2 + 1) * N_SECTORS
            sut_r1, sut_r2 = c1 * 240 + 120, c1 * 240 + 240
            sut_c1, sut_c2 = c2 * 240, c2 * 240 + 120
            T_mrio[r1:r2, c1_idx:c2_idx] = T_sut[sut_r1:sut_r2, sut_c1:sut_c2]

    return T_mrio


def sut_to_mrio_Y(Y_sut, dtype=np.float32):
    """Y from SUT to MRIO format"""
    Y_mrio = np.zeros((MRIO_SIZE, Y_sut.shape[1]), dtype=dtype)

    for c1 in range(N_REGIONS):
        r1, r2 = c1 * N_SECTORS, (c1 + 1) * N_SECTORS
        sut_r1, sut_r2 = c1 * 240 + 120, c1 * 240 + 240
        Y_mrio[r1:r2, :] = Y_sut[sut_r1:sut_r2, :]

    return Y_mrio


def sut_to_mrio_V(V_sut, dtype=np.float32):
    """V from SUT to MRIO format"""
    V_mrio = np.zeros((V_sut.shape[0], MRIO_SIZE), dtype=dtype)

    for c1 in range(N_REGIONS):
        mrio_c1, mrio_c2 = c1 * N_SECTORS, (c1 + 1) * N_SECTORS
        sut_c1, sut_c2 = c1 * 240, c1 * 240 + 120
        V_mrio[:, mrio_c1:mrio_c2] = V_sut[:, sut_c1:sut_c2]

    return V_mrio


def aggregate_Y_by_region(Y_mrio, dtype=np.float32):
    """Aggregate Y from 984 to 164 regions"""
    Y_agg = np.zeros((MRIO_SIZE, N_REGIONS), dtype=dtype)

    for r in range(N_REGIONS):
        col_start = r * N_FD_CATEGORIES
        col_end = col_start + N_FD_CATEGORIES
        Y_agg[:, r] = Y_mrio[:, col_start:col_end].sum(axis=1)

    return Y_agg


def process_year(year):
    """Process a single year"""
    input_path = os.path.join(BASE_INPUT_PATH, str(year))
    zarr_path = os.path.join(OUTPUT_PATH, f'{year}.zarr')

    # Check if already exists
    if os.path.exists(zarr_path):
        print(f"  ⏭️  {year}.zarr already exists, skipping")
        return True

    # Check if input folder exists
    if not os.path.exists(input_path):
        print(f"  ❌ Input folder not found: {input_path}")
        return False

    # Find Markup001 files
    files = os.listdir(input_path)
    t_file, y_file, v_file = None, None, None

    for f in files:
        if 'T-Results' in f and 'Markup001' in f:
            t_file = f
        elif 'Y-Results' in f and 'Markup001' in f:
            y_file = f
        elif 'V-Results' in f and 'Markup001' in f:
            v_file = f

    if not all([t_file, y_file, v_file]):
        print(f"  ❌ Missing Markup001 files for {year}")
        return False

    try:
        # Load raw data
        print(f"  Loading CSV files...")
        T_sut = load_gloria_csv(os.path.join(input_path, t_file))
        Y_sut = load_gloria_csv(os.path.join(input_path, y_file))
        V_sut = load_gloria_csv(os.path.join(input_path, v_file))

        # Convert to MRIO
        print(f"  Converting T matrix...")
        T_mrio = sut_to_mrio_T(T_sut)
        del T_sut
        gc.collect()

        print(f"  Converting Y matrix...")
        Y_mrio = sut_to_mrio_Y(Y_sut)
        del Y_sut
        gc.collect()

        print(f"  Converting V matrix...")
        V_mrio = sut_to_mrio_V(V_sut)
        del V_sut
        gc.collect()

        print(f"  Aggregating Y by region...")
        Y_region = aggregate_Y_by_region(Y_mrio)

        # Reshape for REX compatibility
        T_4d = T_mrio.reshape(N_REGIONS, N_SECTORS, N_REGIONS, N_SECTORS)
        Y_3d = Y_region.reshape(N_REGIONS, N_SECTORS, N_REGIONS)

        # Create Dataset
        ds = xr.Dataset({
            'T': xr.DataArray(
                T_4d,
                dims=['from_region', 'from_sector', 'to_region', 'to_sector'],
                attrs={'description': 'Transaction matrix', 'unit': '1000 USD'}
            ),
            'Y': xr.DataArray(
                Y_3d,
                dims=['from_region', 'from_sector', 'to_region'],
                attrs={'description': 'Final demand (aggregated by region)', 'unit': '1000 USD'}
            ),
            'V': xr.DataArray(
                V_mrio,
                dims=['value_added_category', 'region_sector'],
                attrs={'description': 'Value added', 'unit': '1000 USD'}
            ),
            'Y_full': xr.DataArray(
                Y_mrio,
                dims=['region_sector', 'final_demand'],
                attrs={'description': 'Final demand (full, 6 categories per region)', 'unit': '1000 USD'}
            ),
        })

        ds.attrs['source'] = 'GLORIA MRIO Database Release 060'
        ds.attrs['year'] = year
        ds.attrs['n_regions'] = N_REGIONS
        ds.attrs['n_sectors'] = N_SECTORS
        ds.attrs['valuation'] = 'Basic prices (Markup001)'

        encoding = {
            'T': {'chunks': (50, N_SECTORS, 50, N_SECTORS), 'dtype': 'float32'},
            'Y': {'chunks': (50, N_SECTORS, N_REGIONS), 'dtype': 'float32'},
            'V': {'chunks': (V_mrio.shape[0], 5000), 'dtype': 'float32'},
            'Y_full': {'chunks': (5000, Y_mrio.shape[1]), 'dtype': 'float32'},
        }

        # Save
        print(f"  Saving to zarr...")
        ds.to_zarr(zarr_path, mode='w', consolidated=True, encoding=encoding, zarr_format=2)

        # Verify
        ds_check = xr.open_zarr(zarr_path, consolidated=True)
        t_sum = float(ds_check['T'].sum())
        print(f"  ✅ Saved! T_sum={t_sum:.2e}")
        ds_check.close()

        # Clean up
        del T_mrio, Y_mrio, V_mrio, Y_region, T_4d, Y_3d, ds
        gc.collect()

        return True

    except Exception as e:
        print(f"  ❌ Error: {e}")
        gc.collect()
        return False


