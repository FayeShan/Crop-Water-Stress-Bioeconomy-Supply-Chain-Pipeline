def plot_cell_level(ours_mean, gloria_mean, period_name, used_years, outdir):
    """
    Save cell-level density scatter.
    """
    ours_flat = ours_mean.flatten()
    gloria_flat = gloria_mean.flatten()

    mask = (
        (ours_flat > 0) &
        (gloria_flat > 0) &
        np.isfinite(ours_flat) &
        np.isfinite(gloria_flat)
    )

    x = gloria_flat[mask]
    y = ours_flat[mask]

    r = safe_corr(x, y, method="pearson")
    rho = safe_corr(x, y, method="spearman")

    x_plot, y_plot, z = prepare_density_colors_log(x, y)

    fig, ax = plt.subplots(figsize=(6.5, 5.5))

    if z is not None and len(x_plot) > 0:
        sc = ax.scatter(
            x_plot, y_plot,
            c=z,
            s=10,
            alpha=0.75,
            cmap=DENSITY_CMAP,
            edgecolors="none"
        )
        cbar = plt.colorbar(sc, ax=ax)
        cbar.set_label("Density of points")
    else:
        ax.scatter(x, y, s=10, alpha=0.75)

    ax.set_xscale("log")
    ax.set_yscale("log")

    if len(x_plot) > 0:
        lims = [
            min(x_plot.min(), y_plot.min()) * 0.5,
            max(x_plot.max(), y_plot.max()) * 2
        ]
        ax.plot(lims, lims, linestyle="--", color="red", alpha=0.7, label="1:1 line")
        ax.set_xlim(lims)
        ax.set_ylim(lims)
        ax.legend(frameon=False)

    ax.set_xlabel("GLORIA water stress, period mean (million m³)")
    ax.set_ylabel("CropWS water stress, period mean (million m³)")
    ax.set_title(f"{period_name} | Cell-level\nPearson r = {r:.3f}, Spearman ρ = {rho:.3f}")

    plt.tight_layout()

    png_path = outdir / f"{period_name.replace('-', '_')}_cell_level_density_scatter.png"
    pdf_path = outdir / f"{period_name.replace('-', '_')}_cell_level_density_scatter.pdf"

    plt.savefig(png_path, dpi=FIG_DPI, bbox_inches="tight")
    plt.savefig(pdf_path, bbox_inches="tight")
    plt.close()

    return {
        "period": period_name,
        "level": "cell",
        "pearson_r": r,
        "spearman_rho": rho,
        "n_points": len(x),
        "used_years": ",".join(map(str, used_years)),
        "png": str(png_path),
        "pdf": str(pdf_path),
    }


